/**
 * Starting color tokens from the agreed LinkSonda design, expanded to the full Material 3 scheme.
 *
 * Adaptive mode changes the root roles. Accents mode keeps the green-neutral background and surface
 * ramp while animating primary, secondary and tertiary roles. Static mode always uses green.
 */
internal object LinkSondaPalettes {
    fun scheme(status: AggregateStatus, mode: ThemeMode, dark: Boolean): ColorScheme = when (mode) {
        ThemeMode.ADAPTIVE -> adaptive(status, dark)
        ThemeMode.ACCENTS -> accents(status, dark)
        ThemeMode.STATIC -> green(dark)
    }

    fun adaptive(status: AggregateStatus, dark: Boolean): ColorScheme = when (status) {
        AggregateStatus.AVAILABLE -> green(dark)
        AggregateStatus.PARTIAL -> amber(dark)
        AggregateStatus.UNAVAILABLE -> red(dark)
        AggregateStatus.UNKNOWN -> neutral(dark)
    }

    private fun accents(status: AggregateStatus, dark: Boolean): ColorScheme {
        val base = green(dark)
        val accent = adaptive(status, dark)
        return base.copy(
            primary = accent.primary,
            onPrimary = accent.onPrimary,
            primaryContainer = accent.primaryContainer,
            onPrimaryContainer = accent.onPrimaryContainer,
            inversePrimary = accent.inversePrimary,
            secondary = accent.secondary,
            onSecondary = accent.onSecondary,
            secondaryContainer = accent.secondaryContainer,
            onSecondaryContainer = accent.onSecondaryContainer,
            tertiary = accent.tertiary,
            onTertiary = accent.onTertiary,
            tertiaryContainer = accent.tertiaryContainer,
            onTertiaryContainer = accent.onTertiaryContainer,
            surfaceTint = accent.primary,
            primaryFixed = accent.primaryFixed,
            primaryFixedDim = accent.primaryFixedDim,
            onPrimaryFixed = accent.onPrimaryFixed,
            onPrimaryFixedVariant = accent.onPrimaryFixedVariant,
            secondaryFixed = accent.secondaryFixed,
            secondaryFixedDim = accent.secondaryFixedDim,
            onSecondaryFixed = accent.onSecondaryFixed,
            onSecondaryFixedVariant = accent.onSecondaryFixedVariant,
            tertiaryFixed = accent.tertiaryFixed,
            tertiaryFixedDim = accent.tertiaryFixedDim,
            onTertiaryFixed = accent.onTertiaryFixed,
            onTertiaryFixedVariant = accent.onTertiaryFixedVariant,
        )
    }

